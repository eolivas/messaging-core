using Testcontainers.RabbitMq;

namespace Messaging.MassTransit.Tests;

/// <summary>
/// Shared RabbitMQ Testcontainer fixture for the MassTransit round-trip + dead-letter integration
/// test (task 22.2). One real RabbitMQ broker is started ONCE and shared across every test that
/// joins the <see cref="RabbitMqCollection"/>, so the suite does not pay broker start-up cost per
/// test.
/// </summary>
/// <remarks>
/// <para>
/// The one-engine / real-dependency rule (design + <c>infrastructure.md</c> steering) forbids the
/// MassTransit in-memory transport here: the publish/consume round-trip and dead-letter routing the
/// test asserts are <b>broker</b> behaviours (Req 8.1). Only a real RabbitMQ proves a message is
/// delivered over the wire and, on retry exhaustion, actually leaves the active processing pipeline.
/// This fixture therefore stands up a real broker through <see cref="RabbitMqContainer"/>.
/// </para>
/// <para>
/// The container is owned at process scope and reaped by Testcontainers' Resource Reaper (Ryuk) at
/// process exit, so there is exactly one broker for the whole run even though the fixture is a
/// collection fixture. No secrets are committed: the broker is a local, throwaway container whose
/// credentials are generated by Testcontainers at run time and surfaced only through the live
/// connection string.
/// </para>
/// </remarks>
public sealed class RabbitMqContainerFixture : IAsyncLifetime
{
    private static readonly SemaphoreSlim StartGate = new(1, 1);
    private static RabbitMqContainer? _sharedContainer;

    /// <summary>Starts the shared broker (eagerly for the collection fixture).</summary>
    public Task InitializeAsync() => EnsureStartedAsync();

    /// <summary>
    /// No-op: the single shared container is owned at process scope and reaped by Testcontainers'
    /// Resource Reaper at process exit, so it is not torn down per collection.
    /// </summary>
    public Task DisposeAsync() => Task.CompletedTask;

    /// <summary>
    /// Ensures the shared broker is up, then returns its live AMQP connection string
    /// (<c>amqp://user:pass@host:port</c>) for wiring the native MassTransit RabbitMQ bus.
    /// </summary>
    /// <param name="cancellationToken">Token to cancel start-up.</param>
    public async Task<string> GetConnectionStringAsync(CancellationToken cancellationToken = default)
    {
        var container = await EnsureStartedAsync(cancellationToken).ConfigureAwait(false);
        return container.GetConnectionString();
    }

    /// <summary>
    /// Starts the single shared broker on first call; later calls return the already-started
    /// container. Guarded by a semaphore so concurrent callers (parallel test classes) start exactly
    /// one container.
    /// </summary>
    private static async Task<RabbitMqContainer> EnsureStartedAsync(CancellationToken cancellationToken = default)
    {
        if (_sharedContainer is not null)
        {
            return _sharedContainer;
        }

        await StartGate.WaitAsync(cancellationToken).ConfigureAwait(false);
        try
        {
            if (_sharedContainer is null)
            {
                var container = new RabbitMqBuilder()
                    .WithImage("rabbitmq:3.13-management-alpine")
                    .WithCleanUp(true)
                    .Build();

                await container.StartAsync(cancellationToken).ConfigureAwait(false);
                _sharedContainer = container;
            }
        }
        finally
        {
            StartGate.Release();
        }

        return _sharedContainer;
    }
}

/// <summary>
/// Binds the MassTransit RabbitMQ integration test(s) to the shared
/// <see cref="RabbitMqContainerFixture"/> so a single real broker is reused across the collection.
/// </summary>
[CollectionDefinition(Name)]
public sealed class RabbitMqCollection : ICollectionFixture<RabbitMqContainerFixture>
{
    public const string Name = "rabbitmq-integration";
}
