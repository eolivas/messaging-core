using Messaging.Persistence;
using Messaging.Persistence.Idempotency;
using Messaging.Persistence.Outbox;
using Microsoft.EntityFrameworkCore;
using Testcontainers.PostgreSql;

namespace Messaging.Persistence.Tests;

/// <summary>
/// Shared PostgreSQL Testcontainer fixture for the persistence property/integration tests
/// (tasks 16.3, 16.4, 16.5). One real PostgreSQL container is started ONCE and shared across every
/// test that joins the <see cref="PostgresCollection"/>, so the suite does not pay container
/// start-up cost per test.
/// </summary>
/// <remarks>
/// <para>
/// The one-engine rule (design + <c>infrastructure.md</c> steering) forbids an in-memory DB
/// substitute: the idempotency store's indexed PK lookup and <c>INSERT ... ON CONFLICT DO NOTHING</c>
/// are PostgreSQL semantics and must run against the actual engine. This fixture therefore stands
/// up a real <c>postgres</c> container through <see cref="PostgreSqlContainer"/>.
/// </para>
/// <para>
/// <b>Why initialization is lazy.</b> xUnit drives a collection fixture's
/// <see cref="IAsyncLifetime"/> and injects it through a <c>[Fact]</c>/<c>[Theory]</c> constructor,
/// but <c>FsCheck.Xunit</c>'s <c>[Property]</c> runner neither forwards the collection fixture to
/// the test-class constructor nor guarantees the fixture's async initialization has completed before
/// the property body runs. To work for BOTH kinds of tests, the single container is owned by a
/// process-wide lazy initializer (<see cref="EnsureStartedAsync"/>): the first caller starts the
/// container and creates the schema; everyone else awaits the same task. The container is reaped at
/// process exit by Testcontainers' Resource Reaper (Ryuk), so there is still exactly one container
/// for the whole run.
/// </para>
/// <para>
/// <b>Public API for reuse (16.3/16.4/16.5):</b>
/// <list type="bullet">
/// <item><see cref="CreateContextAsync"/> — ensures the container is up, then returns a fresh
/// <see cref="MessagingDbContext"/> bound to it; each test (or generated property case) uses its own
/// short-lived context, so no test shares EF change-tracker state with another.</item>
/// <item><see cref="GetConnectionStringAsync"/> — ensures the container is up and returns its live
/// connection string, for tests that need raw access.</item>
/// <item><see cref="ResetAsync"/> — truncates <c>messaging_idempotency</c> and
/// <c>messaging_outbox</c> so a test can start from a clean store; property tests that isolate by
/// generating unique keys per case may skip it.</item>
/// </list>
/// </para>
/// <para>
/// Schema is materialized once (via <see cref="DatabaseFacade.EnsureCreatedAsync(CancellationToken)"/>)
/// so the <c>messaging_outbox</c> and <c>messaging_idempotency</c> tables and their indexes exist.
/// No secrets are committed: the container's credentials are generated by Testcontainers at run time
/// and never persisted to source.
/// </para>
/// </remarks>
public sealed class PostgresContainerFixture : IAsyncLifetime
{
    private static readonly SemaphoreSlim StartGate = new(1, 1);
    private static PostgreSqlContainer? _sharedContainer;

    /// <summary>
    /// Lets the collection fixture start the container eagerly for <c>[Fact]</c> tests. For
    /// <c>[Property]</c> tests the same work happens lazily on first <see cref="CreateContextAsync"/>.
    /// </summary>
    public Task InitializeAsync() => EnsureStartedAsync();

    /// <summary>
    /// No-op: the single shared container is owned at process scope and reaped by Testcontainers'
    /// Resource Reaper at process exit, so it is not torn down per collection.
    /// </summary>
    public Task DisposeAsync() => Task.CompletedTask;

    /// <summary>
    /// Ensures the shared container is up, then returns its live connection string.
    /// </summary>
    /// <param name="cancellationToken">Token to cancel start-up.</param>
    public async Task<string> GetConnectionStringAsync(CancellationToken cancellationToken = default)
    {
        var container = await EnsureStartedAsync(cancellationToken).ConfigureAwait(false);
        return container.GetConnectionString();
    }

    /// <summary>
    /// Ensures the shared container is up, then creates a fresh <see cref="MessagingDbContext"/>
    /// bound to it. Callers own the returned context and should dispose it (e.g. <c>await using</c>);
    /// a new context per unit of work keeps tests independent of each other's change-tracker state.
    /// </summary>
    /// <param name="cancellationToken">Token to cancel start-up.</param>
    public async Task<MessagingDbContext> CreateContextAsync(CancellationToken cancellationToken = default)
    {
        var connectionString = await GetConnectionStringAsync(cancellationToken).ConfigureAwait(false);

        var options = new DbContextOptionsBuilder<MessagingDbContext>()
            .UseNpgsql(connectionString)
            .Options;

        return new MessagingDbContext(options);
    }

    /// <summary>
    /// Truncates the messaging tables so a test can begin from a clean store without restarting the
    /// container. Property tests that isolate by generating unique keys per case may skip this.
    /// </summary>
    /// <param name="cancellationToken">Token to cancel the reset.</param>
    public async Task ResetAsync(CancellationToken cancellationToken = default)
    {
        await using var context = await CreateContextAsync(cancellationToken).ConfigureAwait(false);

        // Table names come from the EF mapping constants (single source of truth), so the truncate
        // target never drifts from the mapped tables. These are compile-time constants, not input,
        // so no SQL is built from untrusted data.
        await context.Database
            .ExecuteSqlRawAsync(
                $"TRUNCATE TABLE {IdempotencyRecordConfiguration.TableName}, {OutboxEntryConfiguration.TableName}",
                cancellationToken)
            .ConfigureAwait(false);
    }

    /// <summary>
    /// Starts the single shared container and materializes the schema on first call; later calls
    /// return the already-started container. Guarded by a semaphore so concurrent callers (parallel
    /// test classes) start exactly one container.
    /// </summary>
    private static async Task<PostgreSqlContainer> EnsureStartedAsync(CancellationToken cancellationToken = default)
    {
        if (_sharedContainer is not null)
        {
            return _sharedContainer;
        }

        await StartGate.WaitAsync(cancellationToken).ConfigureAwait(false);
        try
        {
            if (_sharedContainer is null)
            {
                var container = new PostgreSqlBuilder()
                    .WithImage("postgres:16-alpine")
                    .WithDatabase("messaging_core_tests")
                    .WithUsername("messaging")
                    .WithPassword("messaging")
                    .WithCleanUp(true)
                    .Build();

                await container.StartAsync(cancellationToken).ConfigureAwait(false);

                // Materialize messaging_outbox and messaging_idempotency (plus indexes) once.
                var options = new DbContextOptionsBuilder<MessagingDbContext>()
                    .UseNpgsql(container.GetConnectionString())
                    .Options;
                await using (var context = new MessagingDbContext(options))
                {
                    await context.Database.EnsureCreatedAsync(cancellationToken).ConfigureAwait(false);
                }

                _sharedContainer = container;
            }
        }
        finally
        {
            StartGate.Release();
        }

        return _sharedContainer;
    }
}
